#!/usr/bin/env node
/**
 * Writes the SQL that puts the unit-exam paper into Supabase.
 *
 *   node scripts/unit-exam-paper-sql.mjs
 *   → .private/unit-exam-paper.sql   (paste it into the Supabase SQL Editor, after migration 011)
 *
 * The paper comes from `.private/unit-1-exam.public.json`, generated in
 * mr-anas-hq by r04-unit-1-exam/web/make-exam-web.py. It has NO answers — the
 * generator refuses to write one that does, and this script checks again.
 *
 * Same reasoning as dashboard-user.mjs: it prints SQL instead of connecting, so
 * the production key never has to be on this laptop, and the questions never
 * pass through git (this repository is public).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { exit } from 'node:process'

const SRC = '.private/unit-1-exam.public.json'
const OUT = '.private/unit-exam-paper.sql'

const paper = JSON.parse(readFileSync(SRC, 'utf-8'))
const text = JSON.stringify(paper)
for (const key of ['"answer"', '"model"', '"rubric"', '"cells"', '"slot"']) {
  if (text.includes(key)) {
    console.error(`FAIL: the paper contains ${key} — an answer would reach the students.`)
    exit(1)
  }
}
if (text.includes('$paper$')) {
  console.error('FAIL: the paper contains the SQL quote marker.')
  exit(1)
}

const sql = `-- The unit-exam paper (questions only). Generated by scripts/unit-exam-paper-sql.mjs — do not commit.
insert into public.unit_exam_papers (slug, paper, updated_at)
values ('${paper.slug}', $paper$${text}$paper$::jsonb, now())
on conflict (slug) do update set paper = excluded.paper, updated_at = now();

-- Check: one row, ${paper.items.length} questions.
select slug, jsonb_array_length(paper->'items') as questions, updated_at from public.unit_exam_papers;
`
writeFileSync(OUT, sql)
console.log(`written: ${OUT}  (${paper.items.length} questions + bonus, ${Math.round(sql.length / 1024)} KB)`)
