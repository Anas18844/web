/**
 * Reading time, computed from the body so it can never contradict what is
 * actually on the page — a hand-written "٥ دقائق" goes stale the first time a
 * paragraph moves.
 *
 * The rate is 140 words a minute, not the 200 usually quoted for English:
 * Arabic silent reading measures slower, and this is instructional prose with
 * code in it, which is slower again. An inflated rate would make every article
 * on the site report the same number, and a figure that never changes tells a
 * student nothing — which is worse than showing no figure at all.
 */
const WORDS_PER_MINUTE = 140

export function readingMinutes(article: Article): number {
  const words = article.body.reduce((total, block) => {
    const text = block.t === 'ul' || block.t === 'ol' ? block.items.join(' ') : block.x
    return total + text.split(/\s+/).filter(Boolean).length
  }, 0)

  return Math.max(1, Math.round(words / WORDS_PER_MINUTE))
}

/** The reading-time label, pluralised correctly. Used by all three listings. */
export function readingLabel(article: Article): string {
  return arabicPlural(readingMinutes(article), {
    one: 'دقيقة قراية',
    two: 'دقيقتين قراية',
    few: '{n} دقايق قراية',
    many: '{n} دقيقة قراية',
  })
}

export function categoryOf(id: string): Category | undefined {
  return categories.find((c) => c.id === id)
}

/**
 * What the search box actually looks through.
 *
 * Title, standfirst, category and tags — plus the body's HEADINGS, which is
 * where the terms a student types usually live ("الدوال", "أنواع البيانات").
 * Full bodies are deliberately excluded: they would add tens of kilobytes to
 * the page payload to serve a filter over thirteen records, and headings
 * recover most of the recall for almost none of the weight.
 */
export function searchText(article: Article): string {
  const headings = article.body.filter((b) => b.t === 'h').map((b) => (b as { x: string }).x)
  return [
    article.title,
    article.dek,
    categoryOf(article.category)?.label ?? '',
    ...article.tags,
    ...headings,
  ].join(' ')
}

/** Newest first — the order every listing on the site uses. */
export const byDate: readonly Article[] = [...articles].sort((a, b) =>
  b.date.localeCompare(a.date),
)

export const featured: Article = byDate.find((a) => a.featured) ?? byDate[0]

export const rest: readonly Article[] = byDate.filter((a) => a.slug !== featured.slug)

export function findArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug)
}

/** Same category first, then whatever is newest, capped at three. */
export function relatedTo(article: Article, limit = 3): readonly Article[] {
  const sameCategory = byDate.filter(
    (a) => a.slug !== article.slug && a.category === article.category,
  )
  const others = byDate.filter(
    (a) => a.slug !== article.slug && a.category !== article.category,
  )
  return [...sameCategory, ...others].slice(0, limit)
}

const AR_MONTHS = [
  'يناير',
  'فبراير',
  'مارس',
  'أبريل',
  'مايو',
  'يونيو',
  'يوليو',
  'أغسطس',
  'سبتمبر',
  'أكتوبر',
  'نوفمبر',
  'ديسمبر',
]

export function formatDate(iso: string): string {
  const [y, m, d] = iso.split('-').map(Number)
  return `${toArabicDigits(d)} ${AR_MONTHS[m - 1]} ${toArabicDigits(y)}`
}
