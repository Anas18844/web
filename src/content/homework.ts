// ── The public projection ────────────────────────────────────────────────────

export type PublicMcq = Omit<McqQuestion, 'answer'>
/** What the browser may know: the question and its worth, never the answer. */
export type PublicEssay = Omit<EssayQuestion, 'model' | 'rubric' | 'marks'> & {
  marks: number
}

export type PublicHomework = {
  slug: string
  grade: Homework['grade']
  lecture: string
  title: string
  lesson: string
  passMark: number
  maxWords: number
  totalMarks: number
  sections?: Homework['sections']
  mcq: readonly PublicMcq[]
  essay: readonly PublicEssay[]
}

/**
 * Everything the browser is allowed to have.
 *
 * `answer` and `model` are destructured out and thrown away rather than
 * omitted by convention — a `delete` or a hand-written object literal is one
 * careless edit away from leaking, and this projection is the only thing
 * standing between a student and a full answer key.
 */
export function toPublic(hw: Homework): PublicHomework {
  return {
    slug: hw.slug,
    grade: hw.grade,
    lecture: hw.lecture,
    title: hw.title,
    lesson: hw.lesson,
    passMark: hw.passMark,
    maxWords: hw.maxWords,
    totalMarks: totalMarks(hw),
    // Only when set, so every paper without it serialises exactly as it did.
    ...(hw.sections ? { sections: hw.sections } : {}),
    mcq: hw.mcq.map(({ answer: _answer, ...rest }) => rest),
    // `marks` survives; `model` and `rubric` do not. A student needs to know
    // what a question is worth before answering it — that is what tells them
    // the six-mark question wants more than a sentence — and must not be told
    // anything about what the answer is.
    essay: hw.essay.map(({ model: _model, rubric: _rubric, ...rest }) => ({
      ...rest,
      marks: essayMarks({ ...rest, model: '' }),
    })),
  }
}
