import 'server-only'

/**
 * الواجبات — the homework bank.
 *
 * ⚠️ `server-only` is the whole security model of this file.
 *
 * It holds the CORRECT ANSWERS. If it were ever imported into a client
 * component the build would fail — which is the point, because the alternative
 * is a student opening devtools and reading `answer: 2` off every question. The
 * original standalone page shipped the answers to the browser and its own
 * README flagged that as the first thing to fix before going near a platform.
 *
 * So: the page component reads this on the SERVER, strips the answers with
 * `toPublic()`, and sends only what is needed to draw the paper. Marking also
 * happens on the server. The browser never holds a key to this exam.
 */

export type HomeworkImage = { src: string; width: number; height: number }

export type McqQuestion = {
  id: number
  level: 'easy' | 'mid' | 'hard'
  axis: string
  image?: HomeworkImage
  /**
   * Quoted word for word from the ministry's assessment book, and the paper
   * says so with a small badge. Not a secret — it says nothing about the
   * answer — so it survives `toPublic` along with the question.
   */
  official?: boolean
  q: string
  options: readonly string[]
  /** ⚠️ Never leaves the server before a student has submitted. */
  answer: number
}

export type EssayQuestion = {
  id: number
  axis: string
  q: string
  /**
   * What this question is worth. Omitted means `ESSAY_MARK`, which is what
   * every lecture-1 question is.
   *
   * Lecture 2 is where this stopped being an even split: it asks four one-mark
   * recall questions and closes with a six-mark analysis of how AI, ML, DL and
   * GenAI nest inside each other. Marking those the same would either make the
   * definitions worth as much as the analysis, or the analysis worth as little
   * as a definition.
   */
  marks?: number
  /** How the marks divide, for a question worth more than a couple. */
  rubric?: string
  /** ⚠️ Never leaves the server before a student has submitted. */
  model: string
}

export type Homework = {
  slug: string
  grade: 'first_sec' | 'second_bacc'
  lecture: string
  title: string
  lesson: string
  /** Marks needed to pass, out of `totalMarks`. */
  passMark: number
  /** Essay answers longer than this are a sign the student misread the task. */
  maxWords: number
  mcq: readonly McqQuestion[]
  essay: readonly EssayQuestion[]
  /**
   * How the multiple choice is laid out. Absent: one unbroken list, as every
   * paper before lecture 4. `'axis'`: a heading wherever the axis changes, for
   * a paper long enough that eighty questions in one run lose the reader.
   *
   * Opt-in rather than inferred, because lecture 2's axes also sit in
   * contiguous runs and its page was not meant to change.
   */
  sections?: 'axis'
  /**
   * Absent: a lecture's homework. `'bank'`: a unit's question bank — the paper
   * that ships with the unit review video, level 6 of the nine-level ladder in
   * the platform video. It is marked and recorded exactly like homework; only
   * the wording on the page changes, because «ابدأ الواجب» on a hundred-question
   * unit bank tells the student they are late with something they are not.
   */
  kind?: 'bank'
}

/** What an essay is worth unless it says otherwise. */
export const ESSAY_MARK = 2

/** What one essay question is worth. */
export function essayMarks(q: EssayQuestion): number {
  return q.marks ?? ESSAY_MARK
}

/** What the essay section is worth in total. */
export function essayTotal(hw: Homework): number {
  return hw.essay.reduce((t, q) => t + essayMarks(q), 0)
}

export function totalMarks(hw: Homework): number {
  return hw.mcq.length + essayTotal(hw)
}

